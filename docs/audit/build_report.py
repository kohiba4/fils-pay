#!/usr/bin/env python3
"""Builds docs/audit/REPORT.md from the audit docs (stdlib only; never executes repo code).

Sources: findings/*.md (one per bug), TRIAGE.md (verdict per bug), ruled-out/README.md,
suspicious/README.md, DECISIONS.md. REPORT.md is GENERATED: edit the sources, then run

    python3 -I docs/audit/build_report.py
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SEV = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def sections(text):
    """Split a finding file into {heading: body}; header table is parsed separately."""
    out, cur, buf = {}, None, []
    for line in text.split("\n"):
        m = re.match(r"^## (.+)$", line)
        if m:
            if cur is not None:
                out[cur] = "\n".join(buf).strip()
            cur, buf = m.group(1).strip(), []
        elif cur is not None:
            buf.append(line)
    if cur is not None:
        out[cur] = "\n".join(buf).strip()
    return out


def header_fields(text):
    fields = {}
    for m in re.finditer(r"^\| ([A-Za-z ]+) \| (.+) \|$", text, re.M):
        if m.group(1) not in ("Field",):
            fields[m.group(1).strip()] = m.group(2).strip()
    return fields


def first(secs, *prefixes):
    for key, val in secs.items():
        for p in prefixes:
            if key.startswith(p):
                return val
    return "-"


def triage():
    rows = {}
    for line in read(os.path.join(HERE, "TRIAGE.md")).split("\n"):
        m = re.match(r"^\| (AUD-\d{3}) \| ([^|]+) \| ([^|]+) \| (.+) \|$", line)
        if m:
            rows[m.group(1)] = (m.group(2).strip(), m.group(3).strip(), m.group(4).strip())
    return rows


def main():
    verdicts = triage()
    findings = []
    for path in sorted(glob.glob(os.path.join(HERE, "findings", "AUD-*.md"))):
        text = read(path)
        fid = re.match(r"# (AUD-\d{3}) — (.+)", text)
        f = header_fields(text)
        secs = sections(text)
        findings.append({
            "id": fid.group(1), "title": fid.group(2), "file": os.path.basename(path),
            "sev": f.get("Severity", "").strip("*"), "owner": f.get("Owner", "-"),
            "status": f.get("Status", "-"), "category": f.get("Category", "-"),
            "fixcommit": f.get("Fix commit", "-"), "secs": secs,
            "verdict": verdicts.get(fid.group(1), ("MISSING", "-", "add a row to TRIAGE.md")),
        })
    findings.sort(key=lambda x: (SEV.get(x["sev"], 9), x["id"]))

    by_sev, by_ver, fixed = {}, {}, 0
    for x in findings:
        by_sev[x["sev"]] = by_sev.get(x["sev"], 0) + 1
        v = x["verdict"][0].split(" (")[0]
        by_ver[v] = by_ver.get(v, 0) + 1
        if x["status"].lower().startswith("**fixed**") or x["status"].lower().startswith("fixed"):
            fixed += 1

    o = []
    o.append("# FilsPay audit report (generated)\n")
    o.append("> GENERATED by `docs/audit/build_report.py` from findings/, TRIAGE.md, ruled-out/, suspicious/. Do not edit by hand.\n")
    o.append("## 1. Summary\n")
    o.append(f"- Findings: **{len(findings)}** (" + ", ".join(f"{k} {by_sev.get(k, 0)}" for k in SEV) + f"); fixed so far: **{fixed}**.")
    o.append("- By verdict: " + ", ".join(f"{k} {v}" for k, v in sorted(by_ver.items())) + ".")
    o.append("- Not every report item is a defect: see section 4 (design/limitation/hygiene) and section 6 (ruled out).")
    o.append("- Key decisions: [DECISIONS.md](DECISIONS.md). Work split: [TEAM.md](TEAM.md).\n")
    o.append("| ID | Title | Severity | Verdict | Status | Owner |")
    o.append("|---|---|---|---|---|---|")
    for x in findings:
        st = re.sub(r"\*\*", "", x["status"])
        o.append(f"| [{x['id']}](#{x['id'].lower()}) | {x['title']} | {x['sev']} | {x['verdict'][0]} | {st} | {x['owner']} |")

    def block(x):
        s = x["secs"]
        b = [f"### {x['id']}", f"**{x['title']}**\n",
             f"- Severity: **{x['sev']}** · Category: {x['category']} · Owner: {x['owner']}",
             f"- Verdict: **{x['verdict'][0]}** (confidence {x['verdict'][1]}): {x['verdict'][2]}",
             f"- Status: {re.sub(r'[*]{2}', '', x['status'])} · Fix commit: {x['fixcommit']}\n",
             *(["**What is wrong**\n", first(s, "Summary"), ""]
               if first(s, "Summary").rstrip(".").strip() != x["title"].rstrip(".").strip() else []),
             "**Where**\n", first(s, "Location"), "",
             "**Why it happens (root cause)**\n", first(s, "Root cause"), "",
             "**What it breaks (impact)**\n", first(s, "Impact"), "",
             "**Proof / evidence**\n", first(s, "Reproduction"), "",
             "**Fix**\n", first(s, "Fix"), ""]
        rn = first(s, "Re-attack")
        if rn and not rn.startswith("_To be filled"):
            b += ["**Re-attack and side notes**\n", rn, ""]
        rel = first(s, "Related")
        if rel and rel != "-":
            b += [f"**Related:** {rel}\n"]
        b.append(f"_Source file: [findings/{x['file']}](findings/{x['file']})_\n")
        return "\n".join(b)

    real = [x for x in findings if not x["verdict"][0].startswith(("DESIGN", "LIMITATION", "HYGIENE", "UNVERIFIED"))]
    other = [x for x in findings if x not in real]
    o.append("\n## 2. Bugs (by severity)\n")
    for x in real:
        o.append(block(x))
    o.append("\n## 3. Fixed bugs: tests that had to change\n")
    o.append("Collected from the fix sections above (search for 'Tests changed'). Tests were never deleted or weakened; "
             "where an old test asserted a buggy value, only the expected value was corrected, with the reason recorded.\n")
    o.append("\n## 4. Reported but not a code bug (design / limitation / hygiene / unverified)\n")
    for x in other:
        o.append(block(x))
    o.append("\n## 5. Decisions taken\n")
    o.append(read(os.path.join(HERE, "DECISIONS.md")).split("\n", 1)[1])
    o.append("\n## 6. Ruled out (checked and found fine)\n")
    o.append(read(os.path.join(HERE, "ruled-out", "README.md")).split("\n", 1)[1])
    o.append("\n## 7. Traps and injected instructions found\n")
    o.append(read(os.path.join(HERE, "suspicious", "README.md")).split("\n", 1)[1])
    with open(os.path.join(HERE, "REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(o) + "\n")
    print(f"REPORT.md: {len(findings)} findings, {fixed} fixed, verdicts {by_ver}")


if __name__ == "__main__":
    main()
